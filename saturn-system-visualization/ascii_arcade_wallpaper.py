def write_png(path, fb):
    raw = bytearray()
    stride = W * 3
    for y in range(H):
        raw.append(0)
        raw += fb[y * stride:(y + 1) * stride]

    def chunk(tag, data):
        return (struct.pack('>I', len(data)) + tag + data +
                struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff))

    ihdr = struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n')
        f.write(chunk(b'IHDR', ihdr))
        f.write(chunk(b'IDAT', zlib.compress(bytes(raw), 9)))
        f.write(chunk(b'IEND', b''))


def main():
    fb = bytearray(W * H * 3)
    for y in range(H):
        t = y / H
        g = 5 + int(4 * math.sin(math.pi * t))
        r = max(2, g // 3)
        b = max(3, int(g * 0.8))
        fill_rect(fb, 0, y, W, 1, (r, g, b))

    render(fb, glow=True)
    render(fb, glow=False)

    dim = bytes(int(i * 0.85) for i in range(256))
    for y in range(2, H, 3):
        st = y * W * 3
        fb[st:st + W * 3] = fb[st:st + W * 3].translate(dim)

    for y in range(1350, H):
        f = 1.0 - 0.25 * (y - 1350) / (H - 1350)
        table = bytes(int(i * f) for i in range(256))
        st = y * W * 3
        fb[st:st + W * 3] = fb[st:st + W * 3].translate(table)

    write_png(OUT, fb)
    print("written", OUT, W, "x", H)


if __name__ == '__main__':
    main()
