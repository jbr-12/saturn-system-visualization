def fill_rect(fb, x, y, w, h, color):
    x0, y0 = max(0, x), max(0, y)
    x1, y1 = min(W, x + w), min(H, y + h)
    if x1 <= x0 or y1 <= y0:
        return
    rb = bytes(color) * (x1 - x0)
    base = x0 * 3
    row = (x1 - x0) * 3
    for yy in range(y0, y1):
        st = yy * W * 3 + base
        fb[st:st + row] = rb


def draw_text(fb, text, x, y, s, color, pad=0):
    cx = x
    for ch in text:
        rows = FONT.get(ch, FONT['?'])
        for ry, row in enumerate(rows):
            rx = 0
            while rx < 5:
                if row[rx] == '#':
                    rx2 = rx
                    while rx2 + 1 < 5 and row[rx2 + 1] == '#':
                        rx2 += 1
                    fill_rect(fb, cx + rx * s - pad, y + ry * s - pad,
                              (rx2 - rx + 1) * s + 2 * pad, s + 2 * pad, color)
                    rx = rx2 + 1
                else:
                    rx += 1
        cx += 6 * s
    return cx


def draw_pat(fb, pattern, x, y, s, color, pad=0):
    for ry, row in enumerate(pattern):
        rx = 0
        n = len(row)
        while rx < n:
            if row[rx] == '#':
                rx2 = rx
                while rx2 + 1 < n and row[rx2 + 1] == '#':
                    rx2 += 1
                fill_rect(fb, x + rx * s - pad, y + ry * s - pad,
                          (rx2 - rx + 1) * s + 2 * pad, s + 2 * pad, color)
                rx = rx2 + 1
            else:
                rx += 1


